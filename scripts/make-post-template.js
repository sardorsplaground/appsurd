#!/usr/bin/env node
// Derives scripts/post-template.html from the newest committed post,
// replacing the variable parts with {{TOKENS}} used by build-blog.js.
// Rerun after any post-page design/nav change: node scripts/make-post-template.js
const fs = require('fs');
const path = require('path');

const repo = path.join(__dirname, '..');
const SOURCE = 'blog/who-is-leopold-aschenbrenner.html'; // newest hand-written post
const src = fs.readFileSync(path.join(repo, SOURCE), 'utf8');
const CFG = JSON.parse(fs.readFileSync(path.join(__dirname, 'seo-config.json'), 'utf8'));

let out = src;

out = out.replace(/<title>[\s\S]*?<\/title>/, '<title>{{TITLE}} — Appsurd</title>');
out = out.replace(/<meta name="description" content="[\s\S]*?">/, '<meta name="description" content="{{DESCRIPTION}}">');

// The source post carries the static SEO block written by inject-seo.js.
// Swap it for a tokenised version that build-blog.js fills in per post.
const SEO_START = '<!-- SEO:START (generated by scripts/inject-seo.js \u2014 do not hand-edit) -->';
const SEO_END = '<!-- SEO:END -->';
const seoBlock = [
  '<!-- SEO: filled per post by scripts/build-blog.js -->',
  '<link rel="canonical" href="{{CANONICAL}}">',
  '<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">',
  '<meta property="og:type" content="article">',
  `<meta property="og:site_name" content="${CFG.siteName}">`,
  '<meta property="og:locale" content="en_US">',
  '<meta property="og:url" content="{{CANONICAL}}">',
  '<meta property="og:title" content="{{TITLE}}">',
  '<meta property="og:description" content="{{DESCRIPTION}}">',
  '<meta property="og:image" content="{{OG_IMAGE}}">',
  '<meta property="article:published_time" content="{{ISO_DATE}}">',
  '<meta property="article:modified_time" content="{{ISO_UPDATED}}">',
  '<meta property="article:author" content="{{AUTHOR_NAME}}">',
  '<meta name="twitter:card" content="summary_large_image">',
  `<meta name="twitter:site" content="${CFG.twitterHandle}">`,
  '<meta name="twitter:title" content="{{TITLE}}">',
  '<meta name="twitter:description" content="{{DESCRIPTION}}">',
  '<meta name="twitter:image" content="{{OG_IMAGE}}">',
  '{{JSONLD}}',
].join('\n');

const sa = out.indexOf(SEO_START);
const sb = out.indexOf(SEO_END);
if (sa === -1 || sb === -1 || sb < sa) {
  throw new Error(`SEO markers missing from ${SOURCE} \u2014 run node scripts/inject-seo.js first`);
}
out = out.slice(0, sa) + seoBlock + out.slice(sb + SEO_END.length);

out = out.replace(
  /<div class="post-meta">[\s\S]*?<\/div>/,
  `<div class="post-meta">
      <span>{{DATE}}</span>
      <span class="sep">/</span>
      <span>{{AUTHOR}}</span>
      <span class="sep">/</span>
      <span>{{READ_TIME}}</span>
    </div>`
);

out = out.replace(/<h1>[\s\S]*?<\/h1>/, '<h1>{{TITLE_HTML}}</h1>');
out = out.replace(/<p class="lede">[\s\S]*?<\/p>/, '<p class="lede">{{LEDE}}</p>');

const proseStart = out.indexOf('<div class="prose">');
const endcapStart = out.indexOf('<div class="endcap">');
if (proseStart === -1 || endcapStart === -1 || endcapStart < proseStart) {
  throw new Error('Could not locate prose/endcap boundaries');
}
const proseEndTag = out.lastIndexOf('</div>', endcapStart);
out =
  out.slice(0, proseStart) +
  '<div class="prose">\n      {{BODY}}\n    </div>' +
  out.slice(proseEndTag + '</div>'.length);

fs.writeFileSync(path.join(repo, 'scripts/post-template.html'), out);

// {{TITLE}} and {{DESCRIPTION}} legitimately repeat across the meta tags now,
// so those only need to appear at least once.
const TOKENS = ['{{TITLE}}', '{{DESCRIPTION}}', '{{DATE}}', '{{AUTHOR}}', '{{READ_TIME}}',
  '{{TITLE_HTML}}', '{{LEDE}}', '{{BODY}}', '{{CANONICAL}}', '{{OG_IMAGE}}',
  '{{ISO_DATE}}', '{{ISO_UPDATED}}', '{{AUTHOR_NAME}}', '{{JSONLD}}'];
const SINGLE = new Set(['{{DATE}}', '{{AUTHOR}}', '{{READ_TIME}}', '{{TITLE_HTML}}',
  '{{LEDE}}', '{{BODY}}', '{{JSONLD}}']);
for (const t of TOKENS) {
  const n = out.split(t).length - 1;
  if (n < 1) throw new Error(`token ${t} missing from template`);
  if (SINGLE.has(t) && n !== 1) throw new Error(`token ${t} appears ${n} times`);
}
if (/Aschenbrenner/.test(out)) throw new Error('leftover post content in template');
console.log('scripts/post-template.html written,', out.split('\n').length, 'lines');
